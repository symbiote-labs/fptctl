"""Generate the fptctl skill's command reference from the CLI's own docstrings.

Every command documents itself: its docstring is a one-line summary, a description that names
each of its arguments, and an `Examples:` block. `fptctl COMMAND --help` shows that text, and this
script renders the same text, with the options click knows about, into skills/fptctl/. The skill and
the CLI therefore cannot disagree.

    uv run python -m scripts.skill_docs          # rewrite the generated files
    uv run python -m scripts.skill_docs --check  # exit 1 if any generated file is stale
"""

from __future__ import annotations

import argparse
import inspect
import re
import sys
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path

import click

from fptctl.cli import cli

if sys.version_info >= (3, 11):
    import tomllib
else:  # pragma: no cover
    import tomli as tomllib

ROOT = Path(__file__).resolve().parent.parent
SKILL_DIR = ROOT / "skills" / "fptctl"
SKILL_MD = SKILL_DIR / "SKILL.md"
COMMANDS_DIR = SKILL_DIR / "references" / "commands"
DIMENSIONS = ROOT / "parity" / "dimensions.toml"
EXAMPLES_HEADING = "Examples:"
BEGIN = "<!-- BEGIN GENERATED: {name} (scripts/skill_docs.py; edit the CLI docstrings instead) -->"
END = "<!-- END GENERATED: {name} -->"
HEADER = (
    "<!-- Generated by scripts/skill_docs.py from the docstrings in"
    " src/fptctl/commands/{module}.py. Do not edit by hand. -->\n"
)


@dataclass(frozen=True)
class CommandDoc:
    path: tuple[str, ...]
    command: click.Command
    module: str
    summary: str
    body: str
    examples: tuple[str, ...]

    @property
    def name(self) -> str:
        return " ".join(("fptctl", *self.path))


def walk(group: click.Group = cli, path: tuple[str, ...] = ()) -> Iterator[tuple[str, ...]]:
    """Every leaf command's path, in alphabetical order."""
    for name in sorted(group.commands):
        command = group.commands[name]
        if isinstance(command, click.Group):
            yield from walk(command, (*path, name))
        else:
            yield (*path, name)


def resolve(path: tuple[str, ...]) -> click.Command:
    command: click.Command = cli
    for name in path:
        assert isinstance(command, click.Group)
        command = command.commands[name]
    return command


def split_help(text: str) -> tuple[str, str, tuple[str, ...]]:
    """(summary, body, examples) from a command's help text."""
    lines = inspect.cleandoc(text).splitlines()
    summary = lines[0].strip() if lines else ""
    rest = lines[1:]
    examples: list[str] = []
    if EXAMPLES_HEADING in (line.strip() for line in rest):
        start = [line.strip() for line in rest].index(EXAMPLES_HEADING)
        examples = [line.strip() for line in rest[start + 1 :] if line.strip()]
        rest = rest[:start]
    body = "\n".join(line for line in rest if line.strip() != "\b").strip()
    return summary, body, tuple(examples)


def module_of(command: click.Command) -> str:
    callback = command.callback
    assert callback is not None
    return callback.__module__.rsplit(".", 1)[-1]


def command_docs() -> list[CommandDoc]:
    docs = []
    for path in walk():
        command = resolve(path)
        summary, body, examples = split_help(command.help or "")
        docs.append(CommandDoc(path, command, module_of(command), summary, body, examples))
    return docs


def library_methods() -> dict[str, list[str]]:
    """Command name -> the library methods it calls, from parity/dimensions.toml's surfaces."""
    with DIMENSIONS.open("rb") as stream:
        surfaces: dict[str, str] = tomllib.load(stream)["surfaces"]
    methods: dict[str, list[str]] = {}
    for method, surface in sorted(surfaces.items()):
        methods.setdefault(surface, []).append(method)
    return methods


def _context(path: tuple[str, ...]) -> click.Context:
    context = click.Context(cli, info_name="fptctl")
    command: click.Command = cli
    for name in path:
        assert isinstance(command, click.Group)
        command = command.commands[name]
        context = click.Context(command, info_name=name, parent=context)
    return context


def usage(doc: CommandDoc) -> str:
    context = _context(doc.path)
    pieces = " ".join(doc.command.collect_usage_pieces(context))
    return f"{doc.name} {pieces}".strip()


def option_lines(command: click.Command, context: click.Context) -> list[str]:
    lines = []
    help_option = command.get_help_option(context)
    for param in command.get_params(context):
        record = param.get_help_record(context)
        if isinstance(param, click.Option) and record is not None and param is not help_option:
            names, text = record
            lines.append(f"- `{names}`: {' '.join(text.split())}")
    return lines


def _paragraphs(text: str) -> str:
    """Click rewraps docstring paragraphs; markdown should get them unwrapped too."""
    blocks = [" ".join(block.split()) for block in re.split(r"\n\s*\n", text) if block.strip()]
    return "\n\n".join(blocks)


def render_command(doc: CommandDoc, methods: dict[str, list[str]]) -> str:
    context = _context(doc.path)
    parts = [f"## `{doc.name}`", "", doc.summary, ""]
    if doc.body:
        parts += [_paragraphs(doc.body), ""]
    parts += ["```text", usage(doc), "```", ""]
    called = methods.get(" ".join(doc.path))
    if called:
        listed = ", ".join(f"`Shotgun.{name}`" for name in called)
        parts += [f"Library call: {listed}.", ""]
    options = option_lines(doc.command, context)
    if options:
        parts += ["Options:", "", *options, ""]
    parts += ["Examples:", "", "```shell", *doc.examples, "```", ""]
    return "\n".join(parts)


def module_intro(module: str) -> str:
    source = sys.modules[f"fptctl.commands.{module}"]
    return inspect.cleandoc(source.__doc__ or module)


def render_module(module: str, docs: list[CommandDoc], methods: dict[str, list[str]]) -> str:
    intro = module_intro(module)
    title, _, rest = intro.partition("\n")
    parts = [HEADER.format(module=module), f"# {title.rstrip('.')}", ""]
    if rest.strip():
        parts += [_paragraphs(rest), ""]
    for doc in docs:
        parts.append(render_command(doc, methods))
    return "\n".join(parts).rstrip("\n") + "\n"


def render_index(docs: list[CommandDoc]) -> str:
    parts = []
    for module in sorted({doc.module for doc in docs}):
        title = module_intro(module).splitlines()[0].split(":")[0].rstrip(".")
        parts += [
            f"**{title}**: [references/commands/{module}.md](references/commands/{module}.md)"
        ]
        parts += [f"- `{usage(doc)}`: {doc.summary}" for doc in docs if doc.module == module]
        parts.append("")
    return "\n".join(parts).rstrip("\n")


def render_global_options() -> str:
    context = click.Context(cli, info_name="fptctl")
    return "\n".join(option_lines(cli, context))


def replace_region(text: str, name: str, content: str) -> str:
    begin, end = BEGIN.format(name=name), END.format(name=name)
    if begin not in text or end not in text:
        raise ValueError(f"{SKILL_MD.name} is missing the generated region '{name}'")
    head, _, tail = text.partition(begin)
    _, _, tail = tail.partition(end)
    return f"{head}{begin}\n{content}\n{end}{tail}"


def expected_files() -> dict[Path, str]:
    docs = command_docs()
    methods = library_methods()
    files = {
        COMMANDS_DIR / f"{module}.md": render_module(
            module, [doc for doc in docs if doc.module == module], methods
        )
        for module in sorted({doc.module for doc in docs})
    }
    skill = SKILL_MD.read_text(encoding="utf-8")
    skill = replace_region(skill, "global-options", render_global_options())
    files[SKILL_MD] = replace_region(skill, "commands", render_index(docs))
    return files


def stale_files() -> list[Path]:
    """Generated files that differ from the source, plus generated files with no source."""
    expected = expected_files()
    stale = [
        path
        for path, text in expected.items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    ]
    stale += sorted(set(COMMANDS_DIR.glob("*.md")) - set(expected))
    return stale


def write() -> list[Path]:
    expected = expected_files()
    COMMANDS_DIR.mkdir(parents=True, exist_ok=True)
    changed = []
    for path, text in expected.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            changed.append(path)
    for orphan in sorted(set(COMMANDS_DIR.glob("*.md")) - set(expected)):
        orphan.unlink()
        changed.append(orphan)
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is stale")
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_files()
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("Run: uv run python -m scripts.skill_docs", file=sys.stderr)
        return 1 if stale else 0
    for path in write():
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
